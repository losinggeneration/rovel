// Package ui provides a widget toolkit for the tui library.
//
// This package is in active development and its API is subject to change
// before the release (v0.1.0). Breaking changes may occur.
//
// The ui package includes:
//   - Layout containers (VStack, HStack, Split, Padding, Border)
//   - Interactive widgets (Label, Button, TextInput)
//   - Focus management and traversal
//
// # Type Aliases
//
// This package uses type aliases to tui types for ergonomic API:
//   - ui.View is tui.View
//   - ui.ID is tui.ID
//   - ui.Rect is tui.Rect
//   - ui.Size is tui.Size
//   - ui.Painter is tui.Painter
//   - ui.Ctx is tui.Ctx
//   - ui.Event is tui.Event
package ui
